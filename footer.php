(function () {
  const section = document.querySelector('.index_third_section');
  if (!section) return;

  const viewport = section.querySelector('.index_third_slider_viewport');
  const track = section.querySelector('.index_third_cards');
  if (!viewport || !track) return;

  const originalSlides = Array.from(track.children).filter(function (slide) {
    return !slide.hasAttribute('data-index-third-clone');
  });

  if (!originalSlides.length) return;

  let currentIndex = 0;
  let visibleCards = 4;
  let autoTimer = null;
  let resetTimer = null;
  let resizeTimer = null;
  let paused = false;

  const TRANSITION_MS = 680;
  const AUTOPLAY_MS = 2800;

  function cardsPerView() {
    const width = window.innerWidth;
    if (width >= 1200) return 4;
    if (width >= 992) return 3;
    if (width >= 768) return 2;
    return 1;
  }

  function removeClones() {
    track.querySelectorAll('[data-index-third-clone="true"]').forEach(function (clone) {
      clone.remove();
    });
  }

  function addLoopClones() {
    for (let i = 0; i < visibleCards; i++) {
      const source = originalSlides[i % originalSlides.length];
      const clone = source.cloneNode(true);
      clone.setAttribute('data-index-third-clone', 'true');
      clone.setAttribute('aria-hidden', 'true');
      track.appendChild(clone);
    }
  }

  function slideStepWidth() {
    const firstSlide = track.querySelector('.index_third_slide');
    return firstSlide ? firstSlide.getBoundingClientRect().width : 0;
  }

  function setPosition(animate) {
    const step = slideStepWidth();
    track.style.transition = animate
      ? 'transform ' + TRANSITION_MS + 'ms cubic-bezier(.22,.61,.36,1)'
      : 'none';
    track.style.transform = 'translate3d(' + (-(currentIndex * step)) + 'px,0,0)';
  }

  function startAutoplay() {
    clearInterval(autoTimer);
    if (paused) return;
    autoTimer = setInterval(nextSlide, AUTOPLAY_MS);
  }

  function nextSlide() {
    clearTimeout(resetTimer);
    currentIndex += 1;
    setPosition(true);

    if (currentIndex >= originalSlides.length) {
      resetTimer = setTimeout(function () {
        currentIndex = 0;
        setPosition(false);
        /* Force reflow so the next movement animates normally. */
        void track.offsetWidth;
        track.style.transition = 'transform ' + TRANSITION_MS + 'ms cubic-bezier(.22,.61,.36,1)';
      }, TRANSITION_MS + 25);
    }
  }

  function rebuildSlider() {
    clearInterval(autoTimer);
    clearTimeout(resetTimer);

    removeClones();
    visibleCards = cardsPerView();
    addLoopClones();

    currentIndex = 0;
    setPosition(false);
    void track.offsetWidth;
    track.style.transition = 'transform ' + TRANSITION_MS + 'ms cubic-bezier(.22,.61,.36,1)';

    startAutoplay();
  }

  section.addEventListener('mouseenter', function () {
    paused = true;
    clearInterval(autoTimer);
  });

  section.addEventListener('mouseleave', function () {
    paused = false;
    startAutoplay();
  });

  section.addEventListener('focusin', function () {
    paused = true;
    clearInterval(autoTimer);
  });

  section.addEventListener('focusout', function () {
    paused = false;
    startAutoplay();
  });

  document.addEventListener('visibilitychange', function () {
    if (document.hidden) {
      clearInterval(autoTimer);
    } else if (!paused) {
      startAutoplay();
    }
  });

  window.addEventListener('resize', function () {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(rebuildSlider, 180);
  });

  rebuildSlider();
})();
</script>

